/// We capture in Xrgb8888 — the mandatory shm format every wlr client (grim,
/// wf-recorder) understands, and the format both renderers read back cleanly. Argb
/// would advertise an alpha grim then has to flatten; Xrgb is the honest "opaque
/// desktop" format and what wlroots compositors advertise first.
const CAPTURE_FOURCC: Fourcc = Fourcc::Xrgb8888;

/// The protocol version advertised by both backends. 3 is the `buffer_done` level grim
/// uses; one constant so the two `create_global` calls cannot drift.
pub const SCREENCOPY_VERSION: u32 = 3;

/// What a backend must hand this module beyond `CompState`: the queue of copies waiting
/// for a paint. The winit and DRM States each own one; the protocol bodies below never
/// name either State.
pub trait ScreencopyState: CompState + 'static {
    fn pending_screencopy_mut(&mut self) -> &mut Vec<PendingScreencopy>;

    /// A copy was queued. A backend whose render tick skips idle frames (the DRM path's
    /// #137 gate) marks itself damaged here, so the read-back happens on the next tick
    /// rather than after the 200 ms idle heartbeat. The winit loop paints every
    /// iteration, so its default is a no-op.
    fn note_capture_requested(&mut self) {}
}

#[cfg(feature = "winit")]
impl ScreencopyState for crate::winit::State {
    fn pending_screencopy_mut(&mut self) -> &mut Vec<PendingScreencopy> {
        &mut self.pending_screencopy
    }
}

/// Per-frame state (the `zwlr_screencopy_frame_v1` user-data). Holds the region the
/// client asked to capture (validated against the output in `capture_output*`) and a
/// one-shot `used` guard: the protocol says a frame object may be `copy`'d EXACTLY
/// once (`already_used` error otherwise). The raw `Dispatch::request` gives only
/// `&data`, hence interior mutability.
pub struct ScreencopyFrameData {
    /// The capture region in OUTPUT-buffer coordinates (physical px, origin top-left).
    pub region: Rectangle<i32, BufferCoord>,
    /// One-shot guard: a frame object may be `copy`'d EXACTLY once (the protocol's
    /// `already_used` error otherwise). `AtomicBool` (not `Cell`) because wayland-server
    /// requires resource user-data to be `Send + Sync`, and `Cell` is `!Sync`.
    pub used: AtomicBool,
}

/// A `copy`-requested frame awaiting the next paint to be filled from the real
/// framebuffer. Queued on the backend State; drained by the render loop. Owns the frame
/// resource (so it can send `ready`/`failed`) + the client's destination buffer + the
/// region.
pub struct PendingScreencopy {
    pub frame: ZwlrScreencopyFrameV1,
    pub buffer: WlBuffer,
    pub region: Rectangle<i32, BufferCoord>,
    pub with_damage: bool,
}

/// What `copy` does with a request, decided in this order. PURE so the gate is
/// unit-tested on both feature builds without a live State or a client buffer.
///
/// The kill-switch is checked FIRST and wins over everything: a client whose capture is
/// cut learns nothing about its buffer, and its frame is not even marked used, because
/// nothing about that frame has been evaluated. A re-used frame is a protocol error (the
/// spec's `already_used`), which is fatal to the client; a buffer that does not match the
/// advertised format or size is `failed()` (the client may retry with a right one).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CopyVerdict {
    /// The human has cut `screen`: `failed()`, no read-back, nothing learned.
    Blocked,
    /// The frame object was already copied: `already_used` protocol error.
    AlreadyUsed,
    /// The destination is not an shm buffer of the advertised size/format: `failed()`.
    BadBuffer,
    /// Enqueue; the next paint fills it.
    Queue,
}

pub fn copy_admission(capture_blocked: bool, already_used: bool, buffer_matches: bool) -> CopyVerdict {
    if capture_blocked {
        CopyVerdict::Blocked
    } else if already_used {
        CopyVerdict::AlreadyUsed
    } else if !buffer_matches {
        CopyVerdict::BadBuffer
    } else {
        CopyVerdict::Queue
    }
}

/// The shm formats a client may hand `copy`. We advertise Xrgb8888; Argb8888 is the same
/// bytes with an alpha channel the read-back writes as opaque, and grim allocates either.
pub fn client_format_accepted(format: wl_shm::Format) -> bool {
    matches!(format, wl_shm::Format::Xrgb8888 | wl_shm::Format::Argb8888)
}

