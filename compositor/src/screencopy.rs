/// The manager's two capture requests. `CaptureOutput` is the whole output;
/// `CaptureOutputRegion` is clamped to it so a client can never read outside the
/// framebuffer (the ExportMem contract rejects an out-of-bounds region — we clamp rather
/// than fail so a slightly-oversized region still yields a sane capture). HART-comp has
/// exactly ONE output on either backend, so the `output` argument is not consulted.
pub fn manager_request<S>(
    state: &mut S,
    request: zwlr_screencopy_manager_v1::Request,
    data_init: &mut DataInit<'_, S>,
) where
    S: ScreencopyState + Dispatch<ZwlrScreencopyFrameV1, ScreencopyFrameData>,
{
    match request {
        zwlr_screencopy_manager_v1::Request::CaptureOutput {
            frame,
            overlay_cursor: _,
            output: _,
        } => {
            let size = comp_core::output_physical_size(state);
            let region = Rectangle::from_size((size.w, size.h).into());
            init_frame(frame, region, data_init);
        }
        zwlr_screencopy_manager_v1::Request::CaptureOutputRegion {
            frame,
            overlay_cursor: _,
            output: _,
            x,
            y,
            width,
            height,
        } => {
            let out = comp_core::output_physical_size(state);
            let region = comp_core::clamp_region(x, y, width, height, out.w, out.h);
            init_frame(frame, region, data_init);
        }
        zwlr_screencopy_manager_v1::Request::Destroy => {}
        _ => {}
    }
}

/// Create the frame object + tell the client what buffer to allocate (the `buffer`
/// event = format/size/stride, then v3 `buffer_done`). Xrgb8888, 4 bytes/px, stride =
/// width*4. The frame's user-data carries the region so `copy` knows what to read.
fn init_frame<S>(
    frame: New<ZwlrScreencopyFrameV1>,
    region: Rectangle<i32, BufferCoord>,
    data_init: &mut DataInit<'_, S>,
) where
    S: Dispatch<ZwlrScreencopyFrameV1, ScreencopyFrameData>,
{
    let data = ScreencopyFrameData {
        region,
        used: AtomicBool::new(false),
    };
    let frame = data_init.init(frame, data);
    let w = region.size.w as u32;
    let h = region.size.h as u32;
    let stride = w * 4; // Xrgb8888 = 4 bytes per pixel.
    // `buffer` advertises the shm format + dimensions the client must allocate.
    frame.buffer(wl_shm::Format::Xrgb8888, w, h, stride);
    // v3: `buffer_done` says "no more buffer/linux_dmabuf events; pick one + copy".
    if frame.version() >= 3 {
        frame.buffer_done();
    }
}

/// The frame object's requests: `copy` / `copy_with_damage` enqueue the read-back; the
/// render loop fills it. `destroy` is the destructor.
pub fn frame_request<S: ScreencopyState>(
    state: &mut S,
    resource: &ZwlrScreencopyFrameV1,
    request: zwlr_screencopy_frame_v1::Request,
    data: &ScreencopyFrameData,
) {
    match request {
        zwlr_screencopy_frame_v1::Request::Copy { buffer } => {
            queue_copy(state, resource, data, buffer, false);
        }
        zwlr_screencopy_frame_v1::Request::CopyWithDamage { buffer } => {
            queue_copy(state, resource, data, buffer, true);
        }
        zwlr_screencopy_frame_v1::Request::Destroy => {}
        _ => {}
    }
}

/// Validate the client buffer + enqueue the read-back (or `failed()` immediately on a
/// bad buffer / re-use / killswitch). The actual pixel copy happens on the next paint —
/// this only checks + queues. The decision order is `copy_admission`'s.
fn queue_copy<S: ScreencopyState>(
    state: &mut S,
    frame: &ZwlrScreencopyFrameV1,
    data: &ScreencopyFrameData,
    buffer: WlBuffer,
    with_damage: bool,
) {
    let blocked = state.capture_blocked();
    // Not marked used while blocked: the frame was never evaluated.
    let already_used = !blocked && data.used.swap(true, Ordering::SeqCst);
    // The destination MUST be an shm buffer of the advertised size/format. A non-shm
    // (e.g. dmabuf) buffer or a size mismatch fails the copy (we advertised an shm
    // `buffer` event, so a well-behaved client always sends shm). Only read when the
    // two gates above passed, so a cut sense evaluates nothing about the client.
    let expected_w = data.region.size.w;
    let expected_h = data.region.size.h;
    let buffer_matches = !blocked
        && !already_used
        && with_buffer_contents_mut(&buffer, |_ptr, _len, bd: BufferData| {
            client_format_accepted(bd.format) && bd.width == expected_w && bd.height == expected_h
        })
        .unwrap_or_else(|err| {
            debug!(?err, "screencopy: with_buffer_contents_mut could not read the client shm buffer");
            false
        });

    match copy_admission(blocked, already_used, buffer_matches) {
        CopyVerdict::Blocked => {
            info!("screencopy: capture blocked by the screen kill-switch; failing the frame");
            frame.failed();
        }
        CopyVerdict::AlreadyUsed => {
            frame.post_error(
                zwlr_screencopy_frame_v1::Error::AlreadyUsed,
                "screencopy frame already used",
            );
        }
        CopyVerdict::BadBuffer => {
            warn!(
                expected_w,
                expected_h, "screencopy: client buffer is not a matching shm buffer; failing"
            );
            frame.failed();
        }
        CopyVerdict::Queue => {
            state.pending_screencopy_mut().push(PendingScreencopy {
                frame: frame.clone(),
                buffer,
                region: data.region,
                with_damage,
            });
            state.note_capture_requested();
        }
    }
}

/// The kill-switch's queue half: fail every frame already waiting for a paint, so a
/// capture queued a tick before the cut never reads a frame painted before the black
/// surface. Called by each backend's `set_capture_blocked` override when `on` is true.
pub fn fail_pending<S: ScreencopyState>(state: &mut S) {
    fail_pending_frames(state.pending_screencopy_mut());
}

/// `fail_pending` on a queue the caller already holds (the DRM render tick has the
/// queue out of its State while it presents).
pub fn fail_pending_frames(pending: &mut Vec<PendingScreencopy>) {
    for p in pending.drain(..) {
        p.frame.failed();
    }
}

// ════════════════════════════════════════════════════════════════════════════
// The delegate macro: the raw `GlobalDispatch` / `Dispatch` impls for one State, each a
// one-line forward to the generic bodies above. Invoked once per backend below, the way
// Smithay's own `delegate_*!` macros are; the State never names the protocol types.
// ════════════════════════════════════════════════════════════════════════════

macro_rules! delegate_screencopy {
    ($state:ty) => {
        impl GlobalDispatch<ZwlrScreencopyManagerV1, ()> for $state {
            fn bind(
                _state: &mut $state,
                _handle: &DisplayHandle,
                _client: &Client,
                resource: New<ZwlrScreencopyManagerV1>,
                _global_data: &(),
                data_init: &mut DataInit<'_, $state>,
            ) {
                data_init.init(resource, ());
            }
        }

        impl Dispatch<ZwlrScreencopyManagerV1, ()> for $state {
            fn request(
                state: &mut $state,
                _client: &Client,
                _resource: &ZwlrScreencopyManagerV1,
                request: zwlr_screencopy_manager_v1::Request,
                _data: &(),
                _dhandle: &DisplayHandle,
                data_init: &mut DataInit<'_, $state>,
            ) {
                manager_request(state, request, data_init);
            }
        }

        impl Dispatch<ZwlrScreencopyFrameV1, ScreencopyFrameData> for $state {
            fn request(
                state: &mut $state,
                _client: &Client,
                resource: &ZwlrScreencopyFrameV1,
                request: zwlr_screencopy_frame_v1::Request,
                data: &ScreencopyFrameData,
                _dhandle: &DisplayHandle,
                _data_init: &mut DataInit<'_, $state>,
            ) {
                frame_request(state, resource, request, data);
            }
        }
    };
}

