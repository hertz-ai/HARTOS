// ════════════════════════════════════════════════════════════════════════════
// HART-comp — Milestone 6 (headline): zwlr_screencopy_v1 served against HART-comp's
// OWN output framebuffer, so `grim` captures HART-comp DIRECTLY.
// ════════════════════════════════════════════════════════════════════════════
//
// ── Why a hand-rolled protocol module (NOT a Smithay handler) ──
//   The pinned Smithay rev (47843391…) ships the NEWER `ext-image-copy-capture-v1`
//   (src/wayland/image_copy_capture/) but NO `zwlr_screencopy_v1` handler — and
//   `grim` (the de-facto wlroots screenshot tool, what M1-M5 used to capture the
//   HOST) speaks ONLY `zwlr_screencopy_manager_v1`/`zwlr_screencopy_frame_v1`. So
//   we advertise the wlr protocol directly: the bindings ARE in the tree
//   (`wayland_protocols_wlr::screencopy::v1::server`, the `server` feature of the
//   `wayland-protocols-wlr` crate Smithay re-exports), and we impl the RAW
//   `wayland_server::{GlobalDispatch, Dispatch}` traits on each backend's State (NOT
//   Smithay's `Dispatch2`, which is generated by `delegate_dispatch2!(State)` only for
//   the protocols Smithay owns — screencopy is not one, so there is no overlap and no
//   parallel path: this is the SINGLE screencopy implementation in the tree).
//
// ── ONE implementation, TWO backends (NATIVE_OS_PROGRAM 3.3, stream S5) ──
//   Until 2026-09-24 this file was `#![cfg(feature = "winit")]` and named
//   `crate::winit::State` directly, so the DRM backend never registered the global and
//   `grim` on the box said "compositor doesn't support wlr-screencopy-unstable-v1"
//   (docs/VERIFICATION.md row 23). The protocol bodies are now generic over
//   `ScreencopyState` (the backend hands over its queue; everything else comes from
//   `CompState`), and `delegate_screencopy!` stamps the raw `Dispatch` impls onto each
//   State the way Smithay's own delegate macros do. The read-back is generic over
//   `ExportMem`, so the winit path reads its bound window framebuffer and the DRM path
//   reads the scanout slot the `DrmCompositor` just rendered (udev.rs
//   `present_surfaces`), through the SAME `fill_one`.
//
// ── The wire flow (zwlr_screencopy_v1, grim's sequence) ──
//   1. client binds `zwlr_screencopy_manager_v1`, → `capture_output(frame, cursor, output)`
//   2. server creates the `zwlr_screencopy_frame_v1`, sends `buffer(Xrgb8888,w,h,stride)`
//      + (v3) `buffer_done`  — telling the client what to allocate.
//   3. client allocates an shm `wl_buffer` of that size/format, → `copy(buffer)`.
//   4. server reads back its framebuffer into that shm buffer, sends `flags(0)` then
//      `ready(tv_sec_hi, tv_sec_lo, tv_nsec)`.  On any failure → `failed()` (never
//      leave a client hanging — same fail-closed posture as the IPC).
//
//   Steps 1-3 run inline in the protocol handlers below; step 4 (the pixel read-back)
//   is DEFERRED to the render loop (`service_pending_screencopy` /
//   `service_pending_frames`), because the read-back needs the live renderer + the
//   just-painted framebuffer, which only exist inside the backend's render path. Each
//   `copy` enqueues a `PendingScreencopy`; the next paint drains the queue against the
//   real framebuffer. A backend with a frame-budget gate (the DRM path skips idle ticks)
//   is told a copy is waiting through `ScreencopyState::note_capture_requested`, so the
//   next tick paints instead of leaving grim to wait out the idle heartbeat.
//
// ── Kill-switch (constitutional, IPC_PROTOCOL.md §4.11 + §6.4) ──
//   When the human has cut `screen`, screencopy MUST refuse.  That authority lives
//   brain-side (a Python UDS); the compositor can NOT block on it per-frame.  Instead
//   the brain pushes the cut over the EXISTING IPC as `screen.kill {on:true}`, which
//   sets the backend's `capture_blocked` flag.  Every `copy`/`copy_with_damage` checks
//   it and immediately `failed()`s while set — the no-native-capture invariant enforced
//   at the compositor with ZERO per-frame IPC — and a cut ALSO fails every frame already
//   queued (`fail_pending`), so a capture requested a tick before the cut never reads a
//   frame painted before the black surface. Nothing in this protocol can flip the flag:
//   §6.4's "no verb re-enables a cut sense" holds by construction, since the only writer
//   is `CompState::set_capture_blocked`, driven by the brain's edge.  Until the Phase-7
//   portal lands, this is the governed capture path and honours the same gate.

