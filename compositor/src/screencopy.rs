// The render-loop hook — drain queued frames against the JUST-PAINTED framebuffer.
// winit calls it after `frame.finish()` on its bound window framebuffer; the DRM tick
// calls it (through `service_pending_frames`) on the scanout slot the DrmCompositor just
// rendered, bound through `Bind<Dmabuf>`. Both read through `ExportMem`, so it is one
// read-back for both renderers.
// ════════════════════════════════════════════════════════════════════════════

/// Service every queued screencopy frame on `state`: read back the framebuffer region
/// into the client's shm buffer, then send `flags` + `ready` (or `failed`). Drains the
/// queue (every frame is one-shot). `output_transform` is the output's render transform
/// (Flipped180 on winit, Normal on DRM) so the captured pixels match what the user sees
/// upright.
pub fn service_pending_screencopy<S, R>(
    state: &mut S,
    renderer: &mut R,
    framebuffer: &<R as RendererSuper>::Framebuffer<'_>,
    output_size: Size<i32, Physical>,
    output_transform: Transform,
) where
    S: ScreencopyState,
    R: ExportMem,
{
    let mut pending = std::mem::take(state.pending_screencopy_mut());
    service_pending_frames(&mut pending, renderer, framebuffer, output_size, output_transform);
}

/// `service_pending_screencopy` on a queue the caller holds. Empties it.
///
/// The read-back uses `ExportMem::copy_framebuffer` (a glReadPixels on the Gles path, a
/// pixman blit on the floor) → `map_texture` (the CPU-side bytes) → memcpy into the shm
/// map. The captured frame is EXACTLY the displayed frame (cursor + effects + killswitch
/// surface all painted into `framebuffer` already), which is the whole point of
/// capturing HART-comp's own output rather than a host re-composite.
pub fn service_pending_frames<R: ExportMem>(
    pending: &mut Vec<PendingScreencopy>,
    renderer: &mut R,
    framebuffer: &<R as RendererSuper>::Framebuffer<'_>,
    output_size: Size<i32, Physical>,
    output_transform: Transform,
) {
    if pending.is_empty() {
        return;
    }
    for p in pending.drain(..) {
        match fill_one(renderer, framebuffer, &p, output_size, output_transform) {
            Ok(()) => {}
            Err(e) => {
                warn!(error = %e, "screencopy: read-back failed; failing the frame");
                p.frame.failed();
            }
        }
    }
}

/// Read back ONE frame's region + copy it into the client buffer + signal ready.
/// Separated so the `?` early-returns map to a single `failed()` at the call site.
fn fill_one<R: ExportMem>(
    renderer: &mut R,
    framebuffer: &<R as RendererSuper>::Framebuffer<'_>,
    p: &PendingScreencopy,
    output_size: Size<i32, Physical>,
    output_transform: Transform,
) -> Result<(), String> {
    // The framebuffer is stored in the output's RENDER transform (Flipped180 on winit,
    // Normal on DRM). `copy_framebuffer` reads the RAW framebuffer, so to hand the client
    // an upright image we map the logical capture region through the transform to the
    // physical framebuffer rectangle. Flipped180 is a Y-axis flip (x preserved): the
    // mapped rect for a full-output capture is the same rect; for a sub-region only the
    // y origin moves (`area.h - y - height`). Normal is the identity.
    // `Transform::transform_rect_in` does exactly this.
    let fb_region = comp_core::transform_region(p.region, output_size, output_transform);

    // Read back the framebuffer pixels (Xrgb8888) for the region.
    let mapping = renderer
        .copy_framebuffer(framebuffer, fb_region, CAPTURE_FOURCC)
        .map_err(|e| format!("copy_framebuffer: {e:?}"))?;
    let pixels: &[u8] = renderer
        .map_texture(&mapping)
        .map_err(|e| format!("map_texture: {e:?}"))?;

    let src_w = p.region.size.w as usize;
    let src_h = p.region.size.h as usize;
    let src_stride = src_w * 4;
    if pixels.len() < src_stride * src_h {
        return Err(format!(
            "read-back too small: {} < {}",
            pixels.len(),
            src_stride * src_h
        ));
    }

    // Copy into the client's shm buffer row-by-row (honour the client's stride; it may
    // differ from ours if the client over-allocated). The region was already mapped
    // through the transform above and we report no y_invert flag, so a straight row
    // copy is correct here.
    let copied = with_buffer_contents_mut(&p.buffer, |ptr, len, bd: BufferData| {
        let dst_stride = bd.stride as usize;
        let dst_off = bd.offset as usize;
        let rows = src_h.min(bd.height as usize);
        let row_bytes = src_stride.min(dst_stride);
        // Map the shm-format byte order: our read-back is Fourcc::Xrgb8888 (little-
        // endian BGRX in memory, matching wl_shm Xrgb8888), so a direct row copy lands
        // the right bytes for an Xrgb/Argb client buffer.
        // The ONLY unsafe in this crate (see Cargo.toml [lints.rust]): Smithay hands
        // the shm mapping as a raw `*mut u8` + `len`, with no safe write helper for the
        // wlr-screencopy copy at this pinned rev. We build a checked `&mut [u8]` over the
        // mapping ONCE and write rows through safe slicing thereafter.
        // SAFETY: `with_buffer_contents_mut`'s contract guarantees `ptr` is a valid,
        // uniquely-borrowed, writable mapping of exactly `len` bytes for the duration of
        // this closure (it holds the pool lock). `u8` has no alignment/init requirements.
        // No other reference to this mapping exists while the closure runs.
        #[allow(unsafe_code)]
        let dst: &mut [u8] = unsafe { std::slice::from_raw_parts_mut(ptr, len) };
        for row in 0..rows {
            let s = row * src_stride;
            let d = dst_off + row * dst_stride;
            if d + row_bytes > len || s + row_bytes > pixels.len() {
                break;
            }
            dst[d..d + row_bytes].copy_from_slice(&pixels[s..s + row_bytes]);
        }
        rows
    })
    .map_err(|e| format!("with_buffer_contents_mut: {e:?}"))?;

    if copied == 0 {
        return Err("copied 0 rows".into());
    }

    // Tell the client the result is upright (no y-invert; we already corrected the
    // transform), then signal completion with a presentation timestamp.
    p.frame.flags(zwlr_screencopy_frame_v1::Flags::empty());
    if p.with_damage && p.frame.version() >= 2 {
        // We always have full damage on the single output.
        p.frame.damage(
            0,
            0,
            p.region.size.w as u32,
            p.region.size.h as u32,
        );
    }
    let (sec, nsec) = comp_core::now_secs_nsecs();
    let tv_sec_hi = (sec >> 32) as u32;
    let tv_sec_lo = (sec & 0xFFFF_FFFF) as u32;
    p.frame.ready(tv_sec_hi, tv_sec_lo, nsec);
    Ok(())
}

// The PURE region/time helpers — `clamp_region`, `transform_region`, `now_secs_nsecs` —
// live in comp_core.rs (hoisted there while this file was winit-only, so the smithay
// doCheck could exercise them). The handlers above CALL them via `comp_core::` (one
// source of truth, no parallel path); their unit floor stays in comp_core.rs.

/// Whether a wl_shm format has a Fourcc the read-back can target.
#[allow(unused)]
pub(crate) fn shm_supported(format: wl_shm::Format) -> bool {
    shm_format_to_fourcc(format).is_some()
}

// ════════════════════════════════════════════════════════════════════════════
// The gate + format floor. `copy_admission` is the whole `copy` decision and
// `client_format_accepted` the whole format set, both pure, so the kill-switch's
// precedence and the accepted formats are pinned on BOTH feature builds (this file now
// compiles under `--features smithay`, which is what hart-comp.nix's doCheck runs). The
// live half (a real State + client buffer) is the smoke_e2e killswitch round-trip and
// `grim` on the box.
// ════════════════════════════════════════════════════════════════════════════
#[cfg(test)]
mod tests {
    use super::*;

    // ── format invariants ──

    #[test]
    fn capture_fourcc_is_the_mandatory_opaque_format() {
        assert_eq!(CAPTURE_FOURCC, Fourcc::Xrgb8888, "we advertise the opaque Xrgb floor");
        // The `buffer` event names the shm twin of the same format, so a client that
        // allocates exactly what it was told always passes the format gate.
        assert_eq!(shm_format_to_fourcc(wl_shm::Format::Xrgb8888), Some(CAPTURE_FOURCC));
    }

    #[test]
    fn shm_supported_accepts_the_wlr_capture_formats() {
        // grim/wf-recorder always allocate Xrgb8888 or Argb8888 — both must map to a
        // Fourcc (the read-back copies straight into either).
        assert!(shm_supported(wl_shm::Format::Xrgb8888));
        assert!(shm_supported(wl_shm::Format::Argb8888));
    }

    #[test]
    fn the_client_format_set_is_exactly_the_two_8888_shm_formats() {
        assert!(client_format_accepted(wl_shm::Format::Xrgb8888));
        assert!(client_format_accepted(wl_shm::Format::Argb8888));
        // A 16-bit or 10-bit buffer would be row-copied as if it were 4 bytes a pixel,
        // which is garbage for the client and a possible over-read for us.
        assert!(!client_format_accepted(wl_shm::Format::Rgb565));
        assert!(!client_format_accepted(wl_shm::Format::Xrgb2101010));
        assert!(!client_format_accepted(wl_shm::Format::Abgr8888));
    }

    // ── the kill-switch gate (IPC_PROTOCOL 4.11 point 3, 6.4) ──

    #[test]
    fn a_cut_screen_refuses_every_copy_before_anything_else_is_evaluated() {
        // Blocked wins over a fresh, valid request...
        assert_eq!(copy_admission(true, false, true), CopyVerdict::Blocked);
        // ...and over a re-used frame and a bad buffer: a cut sense learns nothing about
        // the request and reports nothing but `failed`.
        assert_eq!(copy_admission(true, true, true), CopyVerdict::Blocked);
        assert_eq!(copy_admission(true, false, false), CopyVerdict::Blocked);
        assert_eq!(copy_admission(true, true, false), CopyVerdict::Blocked);
    }

    #[test]
    fn an_open_screen_queues_a_valid_copy_and_refuses_the_two_protocol_faults() {
        assert_eq!(copy_admission(false, false, true), CopyVerdict::Queue);
        // A second `copy` on the same frame object is the spec's `already_used`.
        assert_eq!(copy_admission(false, true, true), CopyVerdict::AlreadyUsed);
        assert_eq!(copy_admission(false, true, false), CopyVerdict::AlreadyUsed);
        // A buffer that is not what `buffer` advertised fails the frame.
        assert_eq!(copy_admission(false, false, false), CopyVerdict::BadBuffer);
    }

    #[test]
    fn restoring_the_screen_admits_copies_again_and_nothing_here_can_restore_it() {
        // The gate is a pure function of the flag: the only thing that changes the
        // verdict is the flag the brain drives through `screen.kill`. There is no
        // argument a client could pass that turns Blocked into Queue.
        for used in [false, true] {
            for ok in [false, true] {
                assert_eq!(copy_admission(true, used, ok), CopyVerdict::Blocked);
            }
        }
        assert_eq!(copy_admission(false, false, true), CopyVerdict::Queue);
    }

    // ── the DRM transform: Normal is the identity, so a full-output capture on the box
    //    reads the scanout slot 1:1 (winit's Flipped180 is covered in comp_core.rs) ──

    #[test]
    fn a_normal_output_transform_maps_every_region_to_itself() {
        let out: Size<i32, Physical> = (1600, 900).into();
        for (x, y, w, h) in [(0, 0, 1600, 900), (10, 20, 300, 200), (1500, 800, 100, 100)] {
            let r: Rectangle<i32, BufferCoord> = Rectangle::new((x, y).into(), (w, h).into());
            assert_eq!(comp_core::transform_region(r, out, Transform::Normal), r);
        }
    }

    #[test]
    fn both_backends_advertise_the_same_protocol_version() {
        // grim needs `buffer_done` (v3). Pinned so the DRM global cannot regress to a
        // version whose clients wait forever for an event we never send.
        assert_eq!(SCREENCOPY_VERSION, 3);
    }
}
