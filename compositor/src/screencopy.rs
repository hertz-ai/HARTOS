// ════════════════════════════════════════════════════════════════════════════
// HART-comp — Milestone 6 (headline): zwlr_screencopy_v1 served against HART-comp's
// OWN output framebuffer, so `grim` captures HART-comp DIRECTLY.
// ════════════════════════════════════════════════════════════════════════════
//
// ── Why a hand-rolled protocol module (NOT a Smithay handler) ──
//   The pinned Smithay rev (47843391…) ships the NEWER `ext-image-copy-capture-v1`
//   (src/wayland/image_copy_capture/) but NO `zwlr_screencopy_v1` handler — and
//   `grim` (the de-facto wlroots screenshot tool, what M1-M5 used to capture the
//   HOST) speaks ONLY `zwlr_screencopy_manager_v1`/`zwlr_screencopy_frame_v1`. So
//   we advertise the wlr protocol directly: the bindings ARE in the tree
//   (`wayland_protocols_wlr::screencopy::v1::server`, the `server` feature of the
//   `wayland-protocols-wlr` crate Smithay re-exports), and we impl the RAW
//   `wayland_server::{GlobalDispatch, Dispatch}` traits on `State` (NOT Smithay's
//   `Dispatch2`, which is generated by `delegate_dispatch2!(State)` only for the
//   protocols Smithay owns — screencopy is not one, so there is no overlap and no
//   parallel path: this is the SINGLE screencopy implementation in the tree).
//
// ── Why this is the clean capture path (the M6 ordering rationale) ──
//   Through M5, `grim` had to capture the SWAY HOST that composites HART-comp
//   full-screen (HART-comp advertised no screencopy). That re-composite path can
//   NOT prove HART-comp's own cursor / fade animations / the killswitch black
//   surface — they are HART-comp-internal and the host only sees the final pixels
//   it was handed. Servicing screencopy against HART-comp's OWN framebuffer lets
//   `WAYLAND_DISPLAY=<hart socket> grim x.png` read back exactly what HART-comp
//   painted (cursor + effects included), so screencopy is built FIRST and the other
//   three M6 features are verified THROUGH it.
//
// ── The wire flow (zwlr_screencopy_v1, grim's sequence) ──
//   1. client binds `zwlr_screencopy_manager_v1`, → `capture_output(frame, cursor, output)`
//   2. server creates the `zwlr_screencopy_frame_v1`, sends `buffer(Xrgb8888,w,h,stride)`
//      + (v3) `buffer_done`  — telling the client what to allocate.
//   3. client allocates an shm `wl_buffer` of that size/format, → `copy(buffer)`.
//   4. server reads back its framebuffer into that shm buffer, sends `flags(0)` then
//      `ready(tv_sec_hi, tv_sec_lo, tv_nsec)`.  On any failure → `failed()` (never
//      leave a client hanging — same fail-closed posture as the IPC).
//
//   Steps 1-3 run inline in the protocol handlers below; step 4 (the pixel read-back)
//   is DEFERRED to the render loop (`service_pending_screencopy`), because the
//   read-back needs the live `GlesRenderer` + the just-painted `Framebuffer`, which
//   only exist inside winit.rs's render closure.  Each `copy` enqueues a
//   `PendingScreencopy`; the next paint drains the queue against the real framebuffer.
//
// ── Kill-switch (constitutional, IPC_PROTOCOL.md §6.4 + killswitch_plan) ──
//   When the human has cut `screen`, screencopy MUST refuse.  That authority lives
//   brain-side (a Python UDS); the compositor can NOT block on it per-frame.  Instead
//   the brain pushes the cut over the EXISTING IPC as `screen.kill {on:true}`, which
//   sets `State.capture_blocked`.  Every `copy`/`copy_with_damage` checks it and
//   immediately `failed()`s while set — the no-native-capture invariant enforced at
//   the compositor with ZERO per-frame IPC.  Until the Phase-7 portal lands, this is
//   the governed capture path and honours the same gate.

